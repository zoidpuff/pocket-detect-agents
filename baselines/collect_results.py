#!/usr/bin/env python
"""Collect all baseline evaluations (baselines/outputs/<bench>/<variant>/eval) into results/baselines/{summary_long.csv,HEADLINES.md}.
Uses the cluster-bootstrap summary.csv of the project harness (95% CI over 30% sequence-cluster units).
  .venv/bin/python baselines/collect_results.py"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "baselines/outputs"
HEAD = {
    "ligysis": ["recall_topn", "recall_topn2", "recall_max", "recall_ldca_topn2", "P1K", "RRO"],
    "coach420_mlig": ["success_DCA4_topn", "success_DCA4_topn2"], "holo4k_mlig": ["success_DCA4_topn", "success_DCA4_topn2"],
    "cryptobench": ["recall_topn", "recall_topn2", "recall_max", "P1K"], "pocketwatch": ["recall_topn", "recall_topn2", "recall_max", "P1K"],
    "af_set": ["recall_topn", "recall_topn2", "recall_ldca_topn2", "P1K", "hallucination_rate_topn2"],
    "dimer_assembly": ["recall_DCC12_topn2@interface", "recall_DCA4_topn2@interface", "precision_DCC12_topn2@all", "recall_DCC12_topn2@all"],
    "dimer_chains": ["recall_DCC12_topn2@interface", "recall_DCA4_topn2@interface", "precision_DCC12_topn2@all", "recall_DCC12_topn2@all"],
}
ORDER = ["p2rank_2.4.2", "p2rank_2.5.1", "p2rank_2.5.1_af", "fpocket_4.0.3", "fpocket_4.2.3", "fpocket_4.0.3+PRANK_2.4.2", "fpocket_4.0.3+PRANK_2.5.1",
         "fpocket_4.2.3+PRANK_2.4.2", "fpocket_4.2.3+PRANK_2.5.1", "puresnet", "grasp"]


def load(bench, v):
    ev = OUT / bench / v / "eval"
    if bench == "ligysis":
        f = ev / "orig_frame" / "summary.csv"
    else:
        f = ev / "summary.csv"
    if not f.exists():
        return None
    df = pd.read_csv(f)
    if "stratum" in df.columns:  # eval_dimer.py format
        df["metric"] = df.metric + "@" + df.stratum
        df = df.rename(columns={"n_sites": "n"})
    if "average" in df.columns:  # ligand benchmarks: ligand-level (pooled for counts)
        df = df[df.average.isin(["ligand", "pooled", "count"])].drop_duplicates("metric")
    return df


rows = []
for bdir in sorted(p for p in OUT.iterdir() if p.is_dir() and p.name not in ("inputs", "tmp", "speed200")):
    for vdir in sorted(p for p in bdir.iterdir() if p.is_dir()):
        df = load(bdir.name, vdir.name)
        if df is None:
            continue
        for r in df.itertuples():
            rows.append(dict(benchmark=bdir.name, variant=vdir.name, metric=r.metric, value=r.value, ci_low=r.ci_low, ci_high=r.ci_high, n=getattr(r, "n", None)))
long = pd.DataFrame(rows)
(ROOT / "results/baselines").mkdir(parents=True, exist_ok=True)
long.to_csv(ROOT / "results/baselines/summary_long.csv", index=False)
md = ["# Baseline headline numbers (generated by baselines/collect_results.py; do not edit)\n",
      "Values in %, [95% CI] cluster bootstrap (30% sequence-identity units, 1000 resamples). Ligand benchmarks: ligand-level success. See RUNS.md for versions/inputs.\n"]
for b, mets in HEAD.items():
    sub = long[long.benchmark == b]
    if sub.empty:
        continue
    if mets is None:
        mets = [m for m in sub.metric.unique() if "@" in m][:6]
    md.append(f"\n## {b}\n")
    md.append("| variant | " + " | ".join(mets) + " |\n|---|" + "---|" * len(mets))
    for v in [x for x in ORDER if x in set(sub.variant)] + sorted(set(sub.variant) - set(ORDER)):
        cells = []
        for m in mets:
            r = sub[(sub.variant == v) & (sub.metric == m)]
            if r.empty:
                cells.append("-")
                continue
            r = r.iloc[0]
            if "hallucination" in m or m.startswith(("recall", "success", "P1K", "RRO", "precision")):
                f = 100
            else:
                f = 1
            cells.append(f"{r.value*f:.1f} [{r.ci_low*f:.1f}, {r.ci_high*f:.1f}]" if pd.notna(r.ci_low) else f"{r.value*f:.1f}")
        md.append(f"| {v} | " + " | ".join(cells) + " |")
(ROOT / "results/baselines/HEADLINES.md").write_text("\n".join(md) + "\n")
print("\n".join(md))
