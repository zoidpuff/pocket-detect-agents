#!/usr/bin/env python
"""Descriptive rows (no claims): v2 all_default_s0 run WITHOUT --af-mode ("naive") and naive + drop
pockets with mean pLDDT < 70 (scripts/af_plddt_filter_baseline.py), paired vs the v2 --af-mode PREREG
predictions (seed 0) on the AF set and PocketWatch. Rows were scored through the gate
(scripts/run_test_eval.py, ledger methods desc.v2_naive*); this script only computes the paired
comparisons and hallucination rates (unpruned-model pLDDT) and appends to results/test/v2/DESCRIPTIVE.md.

  .venv/bin/python scripts/descriptive_af_naive.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from pocketdetect.prereg import load_rows, paired  # noqa: E402
from run_prereg_analysis import hallucination_for  # noqa: E402

T = ROOT / "results/test"
REF = {"af_set": "burrow_all_default_s0_af", "pocketwatch": "burrow_small_default_s0_af"}
ROWS = ["desc.v2_naive_all_s0", "desc.v2_naive_plddt70_all_s0"]


def main():
    idx = json.loads((T / "v2/preds/index.json").read_text())
    out = []
    for b, ref in REF.items():
        B = load_rows(b, T / "v2" / b / ref)
        ref_pred = ROOT / idx["runs"][f"{b}/{ref}"]["pred_dir"]
        hb = hallucination_for(b, ref_pred)
        for m in ROWS:
            A = load_rows(b, T / "v2" / b / m)
            pdir = T / "descriptive_v2code/preds" / b / m / "preds"
            ha = hallucination_for(b, pdir)
            for met in (["recall_topn2", "recall_ldca_topn2", "P1K"] if b == "af_set" else ["recall_topn2", "P1K"]):
                c = paired(A, B, met, n_boot=1000)
                out.append({"benchmark": b, "method": m, "reference": f"v2:{ref}", "metric": met, **{k: v for k, v in c.items() if not k.startswith("_")}})
            for k in ha:
                out.append({"benchmark": b, "method": m, "reference": f"v2:{ref}", "metric": k, "a": 100 * ha[k], "b": 100 * hb[k],
                            "diff": 100 * (ha[k] - hb[k]), "ci_low": None, "ci_high": None, "n_rows": None})
    (T / "v2/descriptive_af_naive.json").write_text(json.dumps(out, indent=2, default=str))
    f = lambda x: "–" if x is None else f"{x:.2f}"  # noqa: E731
    L = ["", "## Naive (no --af-mode) and naive + pLDDT<70 pocket filter — paired vs v2 --af-mode PREREG predictions (seed 0)", "",
         "v2 all_default_s0 model in both rows (PocketWatch PREREG variant uses the `small` base). Generated by `scripts/descriptive_af_naive.py`;",
         "rows scored via the gate (ledger `desc.v2_naive*`). Hallucination = pocket mean pLDDT < 50 on the unpruned model and no site within 12 Å "
         "(pooled point values). PocketWatch models carry no pLDDT (B = 100), so AF mode and the filter are no-ops there.", "",
         "| benchmark | method | reference | metric | method | reference | Δ [95% CI] | n |", "|---|---|---|---|---|---|---|---|"]
    for r in out:
        ci = f" [{f(r['ci_low'])}, {f(r['ci_high'])}]" if r.get("ci_low") is not None else ""
        L.append(f"| {r['benchmark']} | {r['method']} | {r['reference']} | {r['metric']} | {f(r['a'])} | {f(r['b'])} | {f(r['diff'])}{ci} | {r['n_rows'] or ''} |")
    with open(T / "v2/DESCRIPTIVE.md", "a") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
