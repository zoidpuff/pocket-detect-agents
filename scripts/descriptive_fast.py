#!/usr/bin/env python
"""Descriptive rows (no claims): BURROW `--preset fast` (results/dev/FREEZE_fast.md, seed 0, PREREG ranker
mapping and AF mode, CPU) on all test benchmarks, paired vs v2 default seed 0 and vs the best baseline
(highest point estimate among the benchmark's PREREG comparators). Rows were scored through the gate
(ledger methods desc.fast_*); this script computes paired Δ + wall-clock and appends to
results/test/v2/DESCRIPTIVE.md.

  .venv/bin/python scripts/descriptive_fast.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "scripts"))

from pocketdetect.prereg import FAMILY1, FAMILY2, load_rows, paired  # noqa: E402

T = ROOT / "results/test"
BASELINES = {"ligysis": ["published:fpocket+PRANK", "fpocket_4.2.3+PRANK_2.4.2"], "ligysis_ni": ["fpocket_4.2.3+PRANK_2.4.2", "p2rank_2.5.1"]}
for ep in FAMILY2:
    BASELINES[ep.benchmark] = list(ep.comparators)


def main():
    fidx = json.loads((T / "descriptive_fastcode/preds/index.json").read_text())
    out, wall = [], []
    for key, r in sorted(fidx["runs"].items()):
        b, v = r["bench"], r["variant"]
        if r["rc"] != 0 or r["n_pred_files"] != r["n_inputs"]:
            sys.exit(f"incomplete {key}")
        ref_v2 = v.replace("desc.fast_", "burrow_").replace("_s0", "_default_s0")
        ep = next((x for x in FAMILY1[:1] + FAMILY2 if x.benchmark == b), None)
        metric, stratum = (ep.metric, ep.stratum) if ep else ("recall_topn2", None)
        mets = [metric] + (["recall_ldca_topn2"] if b in ("ligysis", "ligysis_ni", "af_set") else []) + (["P1K"] if b not in ("coach420_mlig", "holo4k_mlig", "dimer") else [])
        A = load_rows(b, T / "v2" / b / v)
        refs = {f"v2:{ref_v2}": T / "v2" / b / ref_v2}
        comps = {c: T / "v2/comparators" / b / c.replace(":", "_") for c in BASELINES.get(b, [])}
        comps = {c: d for c, d in comps.items() if d.exists()}
        # best baseline = highest point estimate on the endpoint metric
        best = max(comps, key=lambda c: paired(A, load_rows(b, comps[c]), metric, stratum=stratum, n_boot=1)["b"]) if comps else None
        if best:
            refs[f"best baseline: {best}"] = comps[best]
        for rname, rd in refs.items():
            B = load_rows(b, rd)
            for m in mets:
                c = paired(A, B, m, stratum=stratum if m == metric else None, n_boot=1000)
                out.append({"benchmark": b, "method": v, "reference": rname, "metric": m + (f"@{stratum}" if stratum and m == metric else ""),
                            **{k: x for k, x in c.items() if not k.startswith("_") and k not in ("metric", "stratum")}})
        v2run = json.loads((T / "v2/preds/index.json").read_text())["runs"].get(f"{b}/{ref_v2}", {})
        wall.append({"benchmark": b, "variant": v, "n_inputs": r["n_inputs"], "wall_s_fast": r["wall_s"], "device_fast": r["device"],
                     "wall_s_v2_default": v2run.get("wall_s"), "device_v2_default": v2run.get("device")})
    (T / "v2/descriptive_fast.json").write_text(json.dumps({"paired": out, "wall": wall}, indent=2, default=str))
    f = lambda x: "–" if x is None else f"{x:.2f}"  # noqa: E731
    L = ["", "## `--preset fast` (seed 0) — paired vs v2 default seed 0 and vs the best baseline", "",
         f"Models results/dev/freeze_fast/models (FREEZE_fast.md), code {fidx['code_commit'][:10]}, CPU fast backend; rows scored via the gate (ledger `desc.fast_*`). "
         "Generated by `scripts/descriptive_fast.py`. Not a pre-registered model.", "",
         "| benchmark | method | reference | metric | fast | reference | Δ [95% CI] | n |", "|---|---|---|---|---|---|---|---|"]
    for r in out:
        L.append(f"| {r['benchmark']} | {r['method']} | {r['reference']} | {r['metric']} | {f(r['a'])} | {f(r['b'])} | {f(r['diff'])} [{f(r['ci_low'])}, {f(r['ci_high'])}] | {r['n_rows']} |")
    L += ["", "Wall-clock of the test prediction runs (whole benchmark, includes process start-up; node shared with other jobs):", "",
          "| benchmark | variant | n inputs | fast: wall s (device) | v2 default: wall s (device) |", "|---|---|---|---|---|"]
    for w in wall:
        L.append(f"| {w['benchmark']} | {w['variant']} | {w['n_inputs']} | {w['wall_s_fast']} ({w['device_fast']}) | {w['wall_s_v2_default']} ({w['device_v2_default']}) |")
    with open(T / "v2/DESCRIPTIVE.md", "a") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
