#!/usr/bin/env python
"""Render results/test/<version>/DESCRIPTIVE.md (descriptive rows, no claims) from summary.json.

  .venv/bin/python scripts/write_descriptive_md.py --version v2
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def fmt(x, d=2):
    return "–" if x is None else f"{x:.{d}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--version", default="v2")
    a = ap.parse_args()
    R = json.loads((ROOT / "results/test" / a.version / "summary.json").read_text())
    ex = R["descriptive"].get("extra_paired", [])
    groups = [
        ("Ablations A1–A3 (seed 0, v1 formation) — paired vs v1 seed 0", lambda r: r["method"].startswith("desc.abl_") and "floor" not in r["method"]),
        ("A1 fold-disjoint + v2 output floor — paired vs v2 seed 0", lambda r: "fold_disjoint_floor" in r["method"]),
        ("P2Rank retrained on our training set (25 % subset) — paired vs P2Rank 2.5.1 stock and vs v2 seed 0", lambda r: r["method"] == "desc.p2rank_ours"),
        ("Optional AF ranker (v2 all_default_s0 + afr_final_afpdb_pl.json; `all` base also on PocketWatch) — vs v2 PREREG variant and P2Rank -c alphafold",
         lambda r: "afranker" in r["method"]),
    ]
    L = [f"# Descriptive test rows — {a.version} (no claims; not part of the pre-registered families)", "",
         "Generated by `scripts/write_descriptive_md.py` from `summary.json` (`scripts/run_prereg_analysis.py --extra results/test/descriptive/extra.json`).",
         "All rows were scored through the gated `scripts/run_test_eval.py` (ledger method names `desc.*`). Δ in percentage points, paired cluster-bootstrap",
         "95 % CI (30 % sequence clusters, 1,000 resamples) on the benchmark's endpoint metric (LIGYSIS / AF set also DCA4 = `recall_ldca_topn2`).",
         "Hallucination rates are pooled point values (no CI).", ""]
    for title, sel in groups:
        rows = [r for r in ex if sel(r)]
        if not rows:
            continue
        L += [f"## {title}", "", "| benchmark | method | reference | metric | method | reference | Δ [95% CI] | n |", "|---|---|---|---|---|---|---|---|"]
        for r in rows:
            ci = f" [{fmt(r['ci_low'])}, {fmt(r['ci_high'])}]" if r.get("ci_low") is not None else ""
            L.append(f"| {r['benchmark']} | {r['method']} | {r['reference']} | {r['metric']} | {fmt(r['a'])} | {fmt(r['b'])} | {fmt(r['diff'])}{ci} | {r['n_rows'] or ''} |")
        L.append("")
    pps = [r for r in R["descriptive"]["secondary"] if r["metric"] == "pockets_per_structure" and r["method"].startswith("extra:")]
    if pps:
        L += ["## Pockets per structure (extra rows)", "", "| benchmark | method | pockets / structure |", "|---|---|---|"]
        L += [f"| {r['benchmark']} | {r['method'][6:]} | {r['value']:.1f} |" for r in pps]
        L.append("")
    L += ["## Strata (v2 seed 0 vs best baseline)", "",
          "In `SUMMARY.md` § \"Descriptive — strata\": LIGYSIS (endpoint C1) by fold novelty (max Foldseek TM to training) and ligand class "
          "(ion / nucleotide-cofactor / other); AF set (endpoint O5) by fold novelty and site pLDDT band; also O2a–O6 by fold novelty and dimer site class.", "",
          "## Notes", "",
          "- PocketWatch input models carry no pLDDT (B-factor = 100 for every atom), so `--af-mode` pruning/soft occlusion is a no-op there and the "
          "hallucination rate is 0 by construction for every method.",
          "- The AF ranker is tied to its `all_default_s0` base model; its PocketWatch row therefore uses the `all` base (PREREG maps PocketWatch to `small`).",
          "- Ablation models: results/ablations/models/abl_{fold_disjoint,chen11,shuffled}_{all,small}_s0.json (v1 code, worktree 5e13267); "
          "A1+floor models: results/test/descriptive/models/ (v2 formation block, v2 code 0d925b2); P2Rank-ours: baselines/p2rank_ours (results/baselines/P2RANK_OURS.md).", ""]
    (ROOT / "results/test" / a.version / "DESCRIPTIVE.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
