_AA_CACHE: dict[str, bool] = {}


def _is_aa(name: str) -> bool:
    v = _AA_CACHE.get(name)
    if v is None:
        t = gemmi.find_tabulated_residue(name)
        v = bool(t is not None and t.is_amino_acid())
        _AA_CACHE[name] = v
    return v


# ============================================================================ SIFTS
def load_sifts(path: str | os.PathLike = SIFTS_TSV, pdb_ids=None) -> dict:
    """``{pdb: {auth_chain: [(acc, res_beg, res_end, sp_beg, sp_end), ...]}}`` from the SIFTS
    ``pdb_chain_uniprot`` segment table (RES_BEG/RES_END are SEQRES indices = ``label_seq_id``)."""
    import pandas as pd

    df = pd.read_csv(path, sep="\t", comment="#", dtype=str, keep_default_na=False)
    if pdb_ids is not None:
        df = df[df["PDB"].isin(set(pdb_ids))]
    out: dict = defaultdict(lambda: defaultdict(list))
    for r in df.itertuples(index=False):
        try:
            seg = (r.SP_PRIMARY, int(r.RES_BEG), int(r.RES_END), int(r.SP_BEG), int(r.SP_END))
        except ValueError:
            continue
        out[r.PDB][r.CHAIN].append(seg)
    return {k: dict(v) for k, v in out.items()}


def label_seq_to_uniprot(segments, acc: str) -> dict[int, int]:
    """label_seq_id -> UniProt residue number for the segments of one chain mapped to ``acc``."""
    m: dict[int, int] = {}
    for a, rb, re_, sb, _se in segments:
        if a != acc:
            continue
        for ls in range(rb, re_ + 1):
            m[ls] = sb + (ls - rb)
    return m


# ============================================================================ structures
def _read_first_model(path) -> gemmi.Structure:
    st = gemmi.read_structure(str(path))
    st.setup_entities()
    st.remove_hydrogens()
    st.remove_alternative_conformations()  # keeps the first conformer (as pocketdetect.structure)
    while len(st) > 1:
        del st[len(st) - 1]
    return st


def read_entry(path) -> dict:
    """Asymmetric-unit entry as plain arrays (first model, no H, first altloc).

    Returns ``{"protein": {label_asym: chain dict}, "residues": [non-protein residue dicts],
    "cell": (frac 3x3, frac vec, orth 3x3, orth vec) or None, "ops": [(rot 3x3, tran 3)],
    "method": str}``. A protein chain dict has ``auth``, ``label_seq`` (per residue), ``auth_seq``
    (str with icode), ``resname``, ``ca`` (per residue, NaN if absent), ``atoms`` (heavy xyz),
    ``atom_res`` (residue index per atom)."""
    st = _read_first_model(path)
    model = st[0]
    prot: dict = {}
    residues = []
    for ch in model:
        for r in ch:
            heavy = [a for a in r]
            if not heavy:
                continue
            xyz = np.array([[a.pos.x, a.pos.y, a.pos.z] for a in heavy], dtype=np.float64)
            is_poly_aa = r.entity_type == gemmi.EntityType.Polymer and _is_aa(r.name) and r.label_seq is not None
            if is_poly_aa:
                c = prot.get(r.subchain)
                if c is None:
                    c = prot[r.subchain] = {"auth": ch.name, "label_seq": [], "auth_seq": [], "resname": [], "ca": [], "atoms": [], "atom_res": []}
                k = len(c["label_seq"])
                c["label_seq"].append(int(r.label_seq))
                c["auth_seq"].append(f"{r.seqid.num}{r.seqid.icode.strip()}")
                c["resname"].append(r.name)
                ca = r.find_atom("CA", "*")
                c["ca"].append((ca.pos.x, ca.pos.y, ca.pos.z) if ca is not None else (np.nan,) * 3)
                c["atoms"].append(xyz)
                c["atom_res"].append(np.full(len(xyz), k, dtype=np.int32))
            elif not r.is_water():
                residues.append({
                    "resname": r.name, "label_asym": r.subchain, "auth_asym": ch.name,
                    "auth_seq": f"{r.seqid.num}{r.seqid.icode.strip()}",
                    "xyz": xyz, "elements": [a.element.name for a in heavy],
                })
    for c in prot.values():
        c["label_seq"] = np.asarray(c["label_seq"], dtype=np.int64)
        c["ca"] = np.asarray(c["ca"], dtype=np.float64).reshape(-1, 3)
        c["atoms"] = np.concatenate(c["atoms"]) if c["atoms"] else np.zeros((0, 3))
        c["atom_res"] = np.concatenate(c["atom_res"]) if c["atom_res"] else np.zeros(0, np.int32)
    cell = None
    ops = []
    method = st.info["_exptl.method"] if "_exptl.method" in st.info else ""
    if st.cell.is_crystal() and st.cell.a > 1.5 and st.cell.volume > 30:
        sg = st.find_spacegroup()
        if sg is not None:
            cell = (np.array(st.cell.frac.mat.tolist()), np.array(st.cell.frac.vec.tolist()),
                    np.array(st.cell.orth.mat.tolist()), np.array(st.cell.orth.vec.tolist()))
            for op in sg.operations():
                ops.append((np.array(op.rot, dtype=float) / gemmi.Op.DEN, np.array(op.tran, dtype=float) / gemmi.Op.DEN))
    return {"protein": prot, "residues": residues, "cell": cell, "ops": ops, "method": method, "path": str(path)}


def rep_chain_data(entry: dict, auth_chain: str) -> dict | None:
    """The representative chain (author chain id) of an entry read with :func:`read_entry`.
    Several label_asym chains can share an author chain id only for non-polymers, so at most one
    protein chain matches."""
    for la, c in entry["protein"].items():
        if c["auth"] == auth_chain:
            d = dict(c)
            d["label_asym"] = la
            return d
    return None


def read_trans_pdb_ca(path) -> dict[str, np.ndarray]:
    """CA coordinates of an authors' ``*.trans.pdb`` rep chain keyed by residue number+icode."""
    out = {}
    with open(path) as fh:
        for line in fh:
            if line.startswith(("ATOM", "HETATM")) and line[12:16].strip() == "CA":
                key = line[22:27].strip()
                out.setdefault(key, np.array([float(line[30:38]), float(line[38:46]), float(line[46:54])]))
    return out


def to_trans_frame(xyz, R, c0) -> np.ndarray:
    """Authors' ``apply_rotation``: x_T = R (x - c0)."""
    return (np.asarray(xyz, dtype=float) - c0) @ np.asarray(R, dtype=float).T


# ============================================================================ geometry
def kabsch(P: np.ndarray, Q: np.ndarray):
    """Least-squares rigid fit of P onto Q (rows paired): returns R, t, rmsd with Q ~ P R^T + t."""
    P = np.asarray(P, dtype=float)
    Q = np.asarray(Q, dtype=float)
    pc, qc = P.mean(0), Q.mean(0)
    H = (P - pc).T @ (Q - qc)
    U, _S, Vt = np.linalg.svd(H)
    d = np.sign(np.linalg.det(Vt.T @ U.T))
    D = np.diag([1.0, 1.0, d])
    R = Vt.T @ D @ U.T
    t = qc - pc @ R.T
    rmsd = float(np.sqrt(np.mean(np.sum((P @ R.T + t - Q) ** 2, axis=1))))
    return R, t, rmsd


def _symmetry_images(entry: dict, lig_xyz: np.ndarray, chain_tree: cKDTree, chain_centre: np.ndarray, chain_radius: float):
    """Best crystal-symmetry image of a ligand w.r.t. a chain: (min distance, image xyz, label)."""
    if entry["cell"] is None or not entry["ops"]:
        return math.inf, None, ""
    fm, fv, om, ov = entry["cell"]
    f_lig = lig_xyz @ fm.T + fv
    f_cc = chain_centre @ fm.T + fv
    best = (math.inf, None, "")
    for i, (rot, tran) in enumerate(entry["ops"]):
        f_img = f_lig @ rot.T + tran
        shift0 = np.round(f_cc - f_img.mean(0))
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for dz in (-1, 0, 1):
                    if i == 0 and dx == dy == dz == 0 and np.all(shift0 == 0):
                        continue  # identity: already tested
                    sh = shift0 + (dx, dy, dz)
                    xyz = (f_img + sh) @ om.T + ov
                    if np.linalg.norm(xyz.mean(0) - chain_centre) > chain_radius + 15.0:
                        continue
                    d = float(chain_tree.query(xyz, k=1)[0].min())
                    if d < best[0]:
                        best = (d, xyz, f"op{i}+{int(sh[0])},{int(sh[1])},{int(sh[2])}")
    return best


def trimmed_kabsch(P: np.ndarray, Q: np.ndarray, cutoff: float = 2.0, min_frac: float = 0.5, min_pairs: int = 3,
                   max_iter: int = 20):
    """Kabsch fit with iterative outlier rejection (rigid-core superposition).

    Each cycle removes the pairs deviating by more than ``cutoff`` A after the current fit (or, if
    that would leave fewer than ``max(min_pairs, ceil(min_frac * n))`` pairs, the worst 10 %, at
    least one) until every kept pair is within ``cutoff`` or the floor is reached. Returns
    ``R, t, rmsd_core, keep_mask, rmsd_all`` (``rmsd_all`` = RMSD of all pairs under the final fit)."""
    P = np.asarray(P, dtype=float)
    Q = np.asarray(Q, dtype=float)
    n = len(P)
    floor = max(min_pairs, int(math.ceil(min_frac * n)))
    keep = np.ones(n, dtype=bool)
    R, t, rmsd = kabsch(P, Q)
    for _ in range(max_iter):
        dev = np.linalg.norm(P @ R.T + t - Q, axis=1)
        bad = keep & (dev > cutoff)
        if not bad.any() or keep.sum() <= floor:
            break
        if keep.sum() - bad.sum() >= floor:
            keep &= ~bad
        else:
            k = max(1, min(int(keep.sum()) - floor, int(math.ceil(0.1 * keep.sum()))))
            if k <= 0:
                break
            order = np.argsort(np.where(keep, dev, -np.inf))[::-1][:k]
            keep[order] = False
        R, t, rmsd = kabsch(P[keep], Q[keep])
    rmsd_all = float(np.sqrt(np.mean(np.sum((P @ R.T + t - Q) ** 2, axis=1))))
    return R, t, rmsd, keep, rmsd_all


# ============================================================================ ligand keys
def parse_ligand_key(key: str) -> tuple[str, str, str, str]:
    """``pdb_RES_chain_num`` -> (pdb, resname, chain, num). Residue names and chain ids contain no
    underscore in this dataset; the residue number may carry an insertion code."""
    parts = key.split("_")
    if len(parts) != 4:
        raise ValueError(f"unexpected ligand key {key!r}")
    return parts[0].lower(), parts[1], parts[2], parts[3]


def resolve_chain_id(cid: str, label_asyms) -> str | None:
    """Map a PDBe-assembly chain id to an asymmetric-unit label_asym_id: exact match, else the
    longest proper prefix that is a label_asym_id (copy suffix stripped)."""
    if cid in label_asyms:
        return cid
    for k in range(len(cid) - 1, 0, -1):
        if cid[:k] in label_asyms:
            return cid[:k]
    return None


# ============================================================================ per-entry extraction
def extract_entry(pdb: str, path, requests: list[dict], sifts_entry: dict) -> dict:
    """Locate the requested ligand instances in one asymmetric-unit entry and gather, for every
    contacted protein chain mapped to the requested UniProt accession, the data needed to place
    the ligand on a representative chain.

    ``requests``: dicts with ``key`` (ligand key), ``chains`` (PDBe chain ids of contacted protein
    chains), ``acc`` (UniProt accession of the site). Returns a JSON-serialisable dict
    ``{"pdb", "status", "method", "ligands": {"key|acc": {...}}, "chains": {"label_asym|acc": {...}}}``; per
    ligand: ``status``, ``match`` (``exact`` / ``suffix`` / ``num`` / ``name``), ``resname``,
    ``elements``, ``placements`` = list of {chain, image, mind, xyz, res: [[up, dist], ...]}; per
    chain: ``auth``, ``acc``, ``up`` and ``ca`` of all UniProt-mapped residues with a CA."""
    out = {"pdb": pdb, "status": "ok", "method": "", "ligands": {}, "chains": {}}
    try:
        entry = read_entry(path)
    except Exception as e:  # noqa: BLE001
        out["status"] = f"read_error:{type(e).__name__}"
        return out
    out["method"] = entry["method"]
    prot = entry["protein"]
    labels = set(prot) | {r["label_asym"] for r in entry["residues"]}
    by_key = defaultdict(list)
    by_name = defaultdict(list)
    for i, r in enumerate(entry["residues"]):
        by_key[(r["resname"], r["label_asym"], r["auth_seq"])].append(i)
        by_name[r["resname"]].append(i)
    # polymer residues can also be BioLiP ligands (peptides / modified residues): index them lazily
    chain_cache: dict = {}

    def chain_info(la: str, acc: str):
        k = (la, acc)
        if k in chain_cache:
            return chain_cache[k]
        c = prot.get(la)
        res = None
        if c is not None:
            m = label_seq_to_uniprot(sifts_entry.get(c["auth"], []), acc)
            up = np.array([m.get(int(s), -1) for s in c["label_seq"]], dtype=np.int64)
            if (up >= 0).any():
                tree = cKDTree(c["atoms"]) if len(c["atoms"]) else None
                centre = c["atoms"].mean(0)
                radius = float(np.sqrt(((c["atoms"] - centre) ** 2).sum(1)).max())
                res = {"c": c, "up": up, "tree": tree, "centre": centre, "radius": radius}
                ok = (up >= 0) & np.isfinite(c["ca"][:, 0])
                out["chains"][f"{la}|{acc}"] = {"auth": c["auth"], "acc": acc, "up": up[ok].tolist(),
                                                "ca": np.round(c["ca"][ok], 3).tolist()}
        chain_cache[k] = res
        return res

    for req in requests:
        key = req["key"]
        acc = req["acc"]
        if f"{key}|{acc}" in out["ligands"]:
            continue
        rec = {"status": "", "match": "", "resname": "", "acc": acc, "elements": [], "placements": [], "n_atoms": 0}
        out["ligands"][f"{key}|{acc}"] = rec
        try:
            _pdb, resname, lchain, lnum = parse_ligand_key(key)
        except ValueError:
            rec["status"] = "bad_key"
            continue
        rec["resname"] = resname
        # candidate protein chains: PDBe ids -> label_asym, keep chains mapped to acc
        cand_chains = []
        for cid in sorted(req["chains"]):
            la = resolve_chain_id(cid, set(prot))
            if la is not None and la not in cand_chains and chain_info(la, acc) is not None:
                cand_chains.append(la)
        acc_chains = [la for la in sorted(prot) if chain_info(la, acc) is not None]
        if not acc_chains:
            rec["status"] = "no_sifts_chain"
            continue
        # locate the ligand residue
        lres = []
        match = ""
        la_l = resolve_chain_id(lchain, labels)
        if la_l is not None:
            lres = by_key.get((resname, la_l, lnum), [])
            match = "exact" if la_l == lchain else "suffix"
        if not lres:
            lres = [i for i in by_name.get(resname, []) if entry["residues"][i]["auth_seq"] == lnum]
            match = "num"
        if not lres:
            lres = list(by_name.get(resname, []))
            match = "name"
        if not lres:
            # peptide / polymer-residue ligands: look in protein chains (auth number)
            rec["status"] = "ligand_not_found"
            continue
        # choose among candidate residues: the one contacting the candidate chains (identity image)
        chains_try = cand_chains or acc_chains
        best_i, best_d = None, math.inf
        for i in lres:
            xyz = entry["residues"][i]["xyz"]
            for la in chains_try:
                ci = chain_info(la, acc)
                d = float(ci["tree"].query(xyz, k=1)[0].min())
                if d < best_d:
                    best_i, best_d = i, d
        if match == "name" and best_d > PARAMS["contact"]:
            rec["status"] = "ligand_not_found"
            continue
        lig = entry["residues"][best_i]
        lxyz = lig["xyz"]
        rec["match"] = match
        rec["elements"] = lig["elements"]
        rec["n_atoms"] = len(lxyz)
        rec["label_asym"] = lig["label_asym"]
        rec["auth_seq"] = lig["auth_seq"]
        # placements: one per contacted chain (identity or symmetry image)
        use = cand_chains if cand_chains else []
        if not use:
            # PDBe chain ids not resolvable / not mapped to acc: any acc chain in contact
            use = acc_chains
            rec["chains_fallback"] = True
        for la in use:
            ci = chain_info(la, acc)
            d0 = float(ci["tree"].query(lxyz, k=1)[0].min())
            xyz, image, mind = lxyz, "", d0
            if d0 > PARAMS["contact"]:
                ds, xs, lab = _symmetry_images(entry, lxyz, ci["tree"], ci["centre"], ci["radius"])
                if ds <= PARAMS["contact"]:
                    xyz, image, mind = xs, lab, ds
                else:
                    continue
            # per-residue min distance to the ligand (residues mapped to acc, within store_dist)
            c = ci["c"]
            lt = cKDTree(xyz)
            dd = lt.query(c["atoms"], k=1, distance_upper_bound=PARAMS["store_dist"])[0]
            rmin = np.full(len(c["label_seq"]), np.inf)
            np.minimum.at(rmin, c["atom_res"], dd)
            sel = np.flatnonzero(np.isfinite(rmin) & (ci["up"] >= 0))
            rec["placements"].append({
                "chain": la, "image": image, "mind": round(mind, 3),
                "xyz": np.round(xyz, 3).tolist(),
                "res": [[int(ci["up"][j]), round(float(rmin[j]), 2)] for j in sel],
            })
        rec["status"] = "ok" if rec["placements"] else "no_contact"
    return out


# ============================================================================ placement on the rep chain
def place_ligand(key: str, rec: dict, chains: dict, site_up, rep_up_ca: dict[int, np.ndarray],
                 params: dict | None = None) -> tuple[list[dict], list[tuple]]:
    """Superpose every placement (contacted chain) of one ligand instance onto the rep chain.

    ``rec`` / ``chains``: ligand record and chain dict of :func:`extract_entry`; ``rep_up_ca``:
    UniProt number -> CA xyz of the representative chain. Superposition set: UniProt-paired CA of
    the site residues within ``core_dist`` of this ligand copy, +- ``window`` residues; if that
    gives < 4 pairs, all residues within ``env_dist`` of the ligand are added. Rigid-core fit by
    :func:`trimmed_kabsch`; rejected if < ``min_pairs`` pairs or core RMSD > ``rmsd_max``.

    Returns (rows, placed) with one row per placement and ``placed`` = list of
    ``(ident, xyz (k,3) in the rep chain frame, is_ion)`` for accepted placements; ``ident``
    identifies the physical copy (same copy listed under several PDBe assembly ids -> same ident)."""
    p = dict(PARAMS)
    if params:
        p.update(params)
    site = set(int(u) for u in site_up)
    if rec is None or rec.get("status") != "ok":
        st = "missing" if rec is None else rec.get("status", "missing")
        return [{"key": key, "chain": "", "image": "", "status": st, "n_pairs": 0, "n_core": 0, "rmsd": np.nan, "rmsd_all": np.nan, "sup_set": ""}], []
    rows, placed = [], []
    ion = len(rec["elements"]) == 1 or rec["resname"] in ION_RESNAMES
    for pl in rec["placements"]:
        row = {"key": key, "chain": pl["chain"], "image": pl["image"], "status": "", "n_pairs": 0, "n_core": 0,
               "rmsd": np.nan, "rmsd_all": np.nan, "sup_set": "", "match": rec.get("match", "")}
        rows.append(row)
        ch = chains.get(f'{pl["chain"]}|{rec["acc"]}')
        if ch is None:
            row["status"] = "chain_missing"
            continue
        src = {int(u): np.asarray(x, dtype=float) for u, x in zip(ch["up"], ch["ca"])}
        resd = {int(u): float(d) for u, d in pl["res"]}
        core = {u for u, d in resd.items() if d <= p["core_dist"] and u in site}
        sel = set()
        for u in core:
            sel.update(range(u - p["window"], u + p["window"] + 1))
        pairs = sorted(u for u in sel if u in src and u in rep_up_ca)
        sup = "site_core"
        if len(pairs) < max(p["min_pairs"], 4):
            env = {u for u, d in resd.items() if d <= p["env_dist"]}
            pairs = sorted(u for u in env | sel if u in src and u in rep_up_ca)
            sup = "env"
        row["sup_set"] = sup
        row["n_pairs"] = len(pairs)
        if len(pairs) < p["min_pairs"]:
            row["status"] = "too_few_pairs"
            continue
        P = np.array([src[u] for u in pairs])
        Q = np.array([rep_up_ca[u] for u in pairs])
        R, t, rmsd, keep, rmsd_all = trimmed_kabsch(P, Q, cutoff=p["trim_cutoff"], min_frac=p["trim_min_frac"], min_pairs=p["min_pairs"])
        row.update(rmsd=rmsd, rmsd_all=rmsd_all, n_core=int(keep.sum()))
        if rmsd > p["rmsd_max"]:
            row["status"] = "rmsd_gt_max"
            continue
        row["status"] = "ok"
        ident = (key.split("_")[0], rec.get("label_asym"), rec.get("auth_seq"), rec["resname"], pl["chain"], pl["image"])
        placed.append((ident, np.asarray(pl["xyz"], dtype=float) @ R.T + t, ion, len(rows) - 1))
    return rows, placed


def pool_site(placed: list[tuple], rep_atoms: np.ndarray, params: dict | None = None, rep_tree: cKDTree | None = None) -> dict:
    """Pool the accepted placements of one site: drop duplicate copies (same ``ident``), drop
    non-ion atoms closer than ``clash`` to rep-chain protein heavy atoms, and drop the whole set if
    more than ``max_drop_frac`` of its atoms clash. ``placed`` items: (ident, xyz, is_ion, tag).
    Returns ``atoms`` (kept), ``n_atoms_raw``, ``n_clash``, ``dropped_site``, ``n_duplicate``,
    ``kept_tags`` (tags of placements contributing atoms), ``clash_by_tag``."""
    p = dict(PARAMS)
    if params:
        p.update(params)
    seen = set()
    xs, ions, tags = [], [], []
    n_dup = 0
    for ident, xyz, ion, tag in placed:
        if ident in seen:
            n_dup += 1
            continue
        seen.add(ident)
        xs.append(np.asarray(xyz, dtype=float).reshape(-1, 3))
        ions.append(np.full(len(xs[-1]), bool(ion)))
        tags.append(np.full(len(xs[-1]), tag, dtype=object))
    res = {"atoms": np.zeros((0, 3)), "n_atoms_raw": 0, "n_clash": 0, "dropped_site": False, "n_duplicate": n_dup,
           "kept_tags": [], "clash_by_tag": {}}
    if not xs:
        return res
    A = np.concatenate(xs)
    ion = np.concatenate(ions)
    tag = np.concatenate(tags)
    res["n_atoms_raw"] = len(A)
    if rep_tree is None and len(rep_atoms):
        rep_tree = cKDTree(rep_atoms)
    if rep_tree is not None:
        d = rep_tree.query(A, k=1)[0]
        clash = (d < p["clash"]) & ~ion
    else:
        clash = np.zeros(len(A), bool)
    res["n_clash"] = int(clash.sum())
    for tg in dict.fromkeys(tag.tolist()):
        m = tag == tg
        res["clash_by_tag"][tg] = (int((clash & m).sum()), int(m.sum()))
    if clash.sum() > p["max_drop_frac"] * len(A):
        res["dropped_site"] = True
        return res
    res["atoms"] = A[~clash]
    res["kept_tags"] = list(dict.fromkeys(tag[~clash].tolist()))
    return res
