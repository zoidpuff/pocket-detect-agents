"""Ligand heavy-atom coordinates for the LIGYSIS reference sites, placed on the representative chain.

Used for the strict DCA criterion (PREREG C1-strict: minimum distance from a predicted pocket
centre to any heavy atom of any ligand that defines the site, after mapping the site's ligands
onto the representative chain). Builder: ``scripts/build_ligysis_ligands.py``; output and
definitions: ``data/processed/gt/ligysis_lbs/ligand_README.md``.

Identifiers (verified on the data, see README):

* ``LIGYSIS_human_chains_per_lig_MAY_2024.pkl``: ``SEG_ID -> site ID -> {ligand key: {protein
  chains}}``. Ligand key ``<pdb>_<RESNAME>_<chain>_<auth_seq_id[icode]>``. ``<chain>`` and the
  protein chain ids are the chain ids of the PDBe *preferred assembly* file used by LIGYSIS, where
  ``new_auth_asym_id`` is the asymmetric-unit ``label_asym_id`` (struct_asym_id), with a suffix for
  copies generated by a non-first assembly operator (e.g. ``H`` / ``HA``). The residue number is the
  author residue number.
* Site residues: ``up_aas`` = UniProt numbers; ``aas`` = **label_seq_ids** of the representative
  chain (verified on the mirror: e.g. 1a52_A site residues 43.. = author 339..; re-computed CA
  centroids match the authors' centres to 0.0005 Å median, scripts/build_gt_ligysis.py). This
  module pairs residues by UniProt number through SIFTS and never uses ``aas``.
* Representative chain ``<pdb>_<auth_asym_id>``; its frame (``PDB_orig_centroids`` /
  ``PDB_rot_matrices``) is the wwPDB asymmetric-unit chain (frame check in the README).

Ligand coordinates are read from wwPDB asymmetric-unit mmCIFs (local mirror). A ligand copy that
only touches a protein chain through a crystal-symmetry operator (assembly copies) is placed with
the symmetry image that brings it into contact with that chain. Each contacted protein chain that
is SIFTS-mapped to the site's UniProt accession is superposed (Kabsch on CA atoms, residues paired
by UniProt number, local residue set around the ligand) onto the representative chain and the
ligand heavy atoms are transformed with it; one ligand instance can therefore yield several
placements (homo-oligomer interface sites).
"""

