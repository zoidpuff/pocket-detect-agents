PARAMS = {
    "contact": 5.0,        # A; ligand heavy atom to protein heavy atom: ligand "contacts" a chain
    "core_dist": 6.0,      # A; site residues within this of the ligand form the local superposition core
    "window": 2,           # +- residues (UniProt numbering) added around core residues
    "env_dist": 8.0,       # A; fallback superposition set: residues with a heavy atom this close to the ligand
    "min_pairs": 3,        # minimum CA pairs for a superposition
    "rmsd_max": 2.0,       # A; reject superpositions whose core CA RMSD exceeds this
    "trim_cutoff": 2.0,    # A; outlier rejection cutoff of the iterative (rigid-core) Kabsch fit
    "trim_min_frac": 0.5,  # the rigid core keeps at least this fraction of the CA pairs
    "clash": 2.2,          # A; drop (non-ion) ligand atoms closer than this to rep-chain protein heavy atoms
    "max_drop_frac": 0.5,  # drop the whole site ligand set if more than this fraction of atoms is dropped
    "store_dist": 12.0,    # A; residues stored per (ligand, chain) in the cache
}

